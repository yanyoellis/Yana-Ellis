let activeProjectId = null;
let activeProjectFilter = "all";
let lastFocusedProjectCard = null;

function getProfileLanguage() {
  const language = document.documentElement.lang || localStorage.getItem("yana-ellis-language") || "en";
  return ["en", "uk", "pl", "ru", "de"].includes(language) ? language : "en";
}

function localText(value, language) {
  return value?.[language] || value?.en || "";
}

function projectTypeLabel(project, language) {
  return projectUiCopy[language]?.[project.type] || projectUiCopy.en[project.type];
}

function translatedSectionTitle(title, language) {
  return projectUiCopy[language]?.sectionTranslations?.[title] || title;
}

function translatedSections(project, language) {
  return project.sections[language] || project.sections.en;
}

function renderProjectCards() {
  const grid = document.getElementById("project-card-grid");
  const index = document.getElementById("case-study-index");
  if (!grid || !index) return;

  const language = getProfileLanguage();
  const ui = projectUiCopy[language] || projectUiCopy.en;
  const visibleProjects = projectExperience.filter((project) => activeProjectFilter === "all" || project.filters.includes(activeProjectFilter));

  grid.innerHTML = visibleProjects
    .map((project) => `
      <button class="project-case-card" type="button" data-project-id="${project.id}" aria-controls="case-modal">
        <span class="project-case-number">${project.number}</span>
        <span class="project-case-type">${projectTypeLabel(project, language)}${project.location ? ` · ${project.location}` : ""}</span>
        <strong>${localText(project.title, language)}</strong>
        <span class="project-case-business">${localText(project.business, language)}</span>
        <span class="project-case-role">${project.role}</span>
        <span class="project-case-cta">${ui.view} ↗</span>
      </button>
    `)
    .join("");

  index.innerHTML = projectExperience.map((project) => renderCaseArticle(project, language, true)).join("");

  grid.querySelectorAll(".project-case-card").forEach((card) => {
    card.addEventListener("click", () => openCase(card.dataset.projectId, card));
  });
}

function renderCaseArticle(project, language, hidden = false) {
  const ui = projectUiCopy[language] || projectUiCopy.en;
  const sections = translatedSections(project, language);
  return `
    <article class="case-study-article"${hidden ? ` id="case-index-${project.id}"` : ""}>
      <header class="case-study-header">
        <p class="section-kicker">${project.number} · ${projectTypeLabel(project, language)}${project.location ? ` · ${project.location}` : ""}</p>
        <h2${hidden ? "" : ` id="case-modal-title"`}>${localText(project.title, language)}</h2>
        <p class="case-study-business">${localText(project.business, language)}</p>
        <p class="case-study-role"><span>${ui.roleLabel}</span>${project.role}</p>
      </header>
      <div class="case-study-body" aria-label="${ui.sectionsNote}">
        ${sections.map(([title, body]) => `
          <section>
            <h3>${translatedSectionTitle(title, language)}</h3>
            <p>${body}</p>
          </section>
        `).join("")}
      </div>
    </article>
  `;
}

function openCase(projectId, trigger) {
  const project = projectExperience.find((item) => item.id === projectId);
  const modal = document.getElementById("case-modal");
  const content = document.getElementById("case-modal-content");
  const panel = modal?.querySelector(".case-modal-panel");
  if (!project || !modal || !content || !panel) return;

  activeProjectId = projectId;
  lastFocusedProjectCard = trigger || document.activeElement;
  content.innerHTML = renderCaseArticle(project, getProfileLanguage());
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("case-modal-open");
  panel.focus({ preventScroll: true });
  history.replaceState(null, "", `#${projectId}`);
}

function closeCase(updateHash = true) {
  const modal = document.getElementById("case-modal");
  if (!modal || modal.getAttribute("aria-hidden") === "true") return;
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("case-modal-open");
  activeProjectId = null;
  if (updateHash && window.location.hash) {
    history.replaceState(null, "", window.location.pathname + window.location.search);
  }
  if (lastFocusedProjectCard && typeof lastFocusedProjectCard.focus === "function") {
    lastFocusedProjectCard.focus({ preventScroll: true });
  }
}

function refreshOpenCase() {
  if (!activeProjectId) return;
  const project = projectExperience.find((item) => item.id === activeProjectId);
  const content = document.getElementById("case-modal-content");
  if (project && content) content.innerHTML = renderCaseArticle(project, getProfileLanguage());
}

function trapCaseFocus(event) {
  const modal = document.getElementById("case-modal");
  if (!modal || modal.getAttribute("aria-hidden") === "true" || event.key !== "Tab") return;
  const focusable = modal.querySelectorAll('button, [href], [tabindex]:not([tabindex="-1"])');
  const first = focusable[0];
  const last = focusable[focusable.length - 1];
  if (!first || !last) return;
  if (event.shiftKey && document.activeElement === first) {
    event.preventDefault();
    last.focus();
  } else if (!event.shiftKey && document.activeElement === last) {
    event.preventDefault();
    first.focus();
  }
}

document.addEventListener("DOMContentLoaded", () => {
  renderProjectCards();

  document.querySelectorAll("[data-project-filter]").forEach((button) => {
    button.addEventListener("click", () => {
      activeProjectFilter = button.dataset.projectFilter;
      document.querySelectorAll("[data-project-filter]").forEach((filterButton) => {
        filterButton.classList.toggle("is-active", filterButton === button);
      });
      renderProjectCards();
    });
  });

  document.querySelectorAll("[data-case-close]").forEach((button) => {
    button.addEventListener("click", () => closeCase());
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeCase();
    trapCaseFocus(event);
  });

  document.querySelectorAll(".language-button").forEach((button) => {
    button.addEventListener("click", () => setTimeout(() => {
      renderProjectCards();
      refreshOpenCase();
    }, 0));
  });

  const directProject = projectExperience.find((project) => `#${project.id}` === window.location.hash);
  if (directProject) {
    const card = document.querySelector(`[data-project-id="${directProject.id}"]`);
    openCase(directProject.id, card);
  }
});
