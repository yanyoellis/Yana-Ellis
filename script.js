const languageButtons = document.querySelectorAll(".language-button");
const textNodes = document.querySelectorAll("[data-i18n]");
const altNodes = document.querySelectorAll("[data-i18n-alt]");
const ariaNodes = document.querySelectorAll("[data-i18n-aria]");
const projectCards = document.querySelectorAll(".project-card");
const projectsViewport = document.querySelector(".projects-viewport");
const projectsGrid = document.querySelector(".projects-grid");
const projectsPrevious = document.querySelector("#projectsPrevious");
const projectsNext = document.querySelector("#projectsNext");
const estimateButton = document.querySelector("#estimateButton");
const heroEstimateButton = document.querySelector("#heroEstimateButton");
const footerEstimateButton = document.querySelector("#footerEstimateButton");
const marketModal = document.querySelector("#marketModal");
const marketCards = document.querySelectorAll("[data-market]");
const marketCloseButtons = document.querySelectorAll("[data-market-close]");
const supportedLanguages = ["en", "uk", "pl"];
let lastFocusedElement = null;

function getInitialLanguage() {
  const savedLanguage = localStorage.getItem("yana-ellis-language");

  if (supportedLanguages.includes(savedLanguage)) {
    return savedLanguage;
  }

  return "en";
}

function translateProjectLabels(language) {
  const copy = translations[language];

  projectCards.forEach((card) => {
    const projectName = card.dataset.projectName;
    card.setAttribute("aria-label", copy.projectAria.replace("{name}", projectName));
  });
}

function applyLanguage(language) {
  const copy = translations[language] || translations.en;

  document.documentElement.lang = language;
  document.title = copy.documentTitle;
  localStorage.setItem("yana-ellis-language", language);

  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key]) {
      node.textContent = copy[key];
    }
  });

  altNodes.forEach((node) => {
    const key = node.dataset.i18nAlt;
    if (copy[key]) {
      node.setAttribute("alt", copy[key]);
    }
  });

  ariaNodes.forEach((node) => {
    const key = node.dataset.i18nAria;
    if (copy[key]) {
      node.setAttribute("aria-label", copy[key]);
    }
  });

  translateProjectLabels(language);

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function getFocusableElements(container) {
  return Array.from(
    container.querySelectorAll(
      'a[href], button:not([disabled]), textarea, input, select, [tabindex]:not([tabindex="-1"])'
    )
  ).filter((element) => !element.hasAttribute("hidden"));
}

function openMarketModal() {
  if (!marketModal) {
    return;
  }

  lastFocusedElement = document.activeElement;
  marketModal.hidden = false;
  document.body.classList.add("modal-open");

  requestAnimationFrame(() => {
    marketModal.classList.add("is-visible");
    getFocusableElements(marketModal)[0]?.focus();
  });
}

function closeMarketModal() {
  if (!marketModal || marketModal.hidden) {
    return;
  }

  marketModal.classList.remove("is-visible");
  document.body.classList.remove("modal-open");

  window.setTimeout(() => {
    marketModal.hidden = true;
    (lastFocusedElement || estimateButton)?.focus();
  }, 220);
}

function keepFocusInsideModal(event) {
  if (!marketModal || marketModal.hidden || event.key !== "Tab") {
    return;
  }

  const focusableElements = getFocusableElements(marketModal);
  const firstElement = focusableElements[0];
  const lastElement = focusableElements[focusableElements.length - 1];

  if (!firstElement || !lastElement) {
    return;
  }

  if (event.shiftKey && document.activeElement === firstElement) {
    event.preventDefault();
    lastElement.focus();
  }

  if (!event.shiftKey && document.activeElement === lastElement) {
    event.preventDefault();
    firstElement.focus();
  }
}

function selectMarket(market) {
  sessionStorage.setItem("yana-ellis-selected-market", market);

  const routes = {
    canada: "calculator/canada/index.html",
    ukraine: "calculator/ukraine/index.html",
    poland: "calculator/poland/index.html"
  };

  window.location.href = routes[market] || routes.canada;
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.lang);
  });
});

estimateButton?.addEventListener("click", openMarketModal);
heroEstimateButton?.addEventListener("click", openMarketModal);
footerEstimateButton?.addEventListener("click", openMarketModal);

marketCloseButtons.forEach((button) => {
  button.addEventListener("click", closeMarketModal);
});

marketCards.forEach((card) => {
  card.addEventListener("click", () => selectMarket(card.dataset.market));
});

document.addEventListener("keydown", (event) => {
  if (!marketModal || marketModal.hidden) {
    return;
  }

  if (event.key === "Escape") {
    closeMarketModal();
  }

  keepFocusInsideModal(event);
});

function getProjectStep() {
  const firstCard = projectsGrid?.querySelector(".project-card");

  if (!firstCard) {
    return 0;
  }

  const gap = Number.parseFloat(getComputedStyle(projectsGrid).columnGap) || 0;
  return firstCard.getBoundingClientRect().width + gap;
}

function updateProjectArrows() {
  if (!projectsViewport || !projectsPrevious || !projectsNext) {
    return;
  }

  const maximumScroll = projectsViewport.scrollWidth - projectsViewport.clientWidth;
  projectsPrevious.disabled = projectsViewport.scrollLeft <= 2;
  projectsNext.disabled = projectsViewport.scrollLeft >= maximumScroll - 2;
}

function moveProjects(direction) {
  projectsViewport?.scrollBy({
    left: getProjectStep() * direction,
    behavior: "smooth"
  });
}

if (projectsViewport && projectsPrevious && projectsNext) {
  projectsPrevious.addEventListener("click", () => moveProjects(-1));
  projectsNext.addEventListener("click", () => moveProjects(1));
  projectsViewport.addEventListener("scroll", updateProjectArrows, { passive: true });
  projectsViewport.addEventListener("keydown", (event) => {
    if (event.key === "ArrowLeft" || event.key === "ArrowRight") {
      event.preventDefault();
      moveProjects(event.key === "ArrowLeft" ? -1 : 1);
    }
  });
  window.addEventListener("resize", updateProjectArrows);
  window.addEventListener("load", updateProjectArrows);
}

applyLanguage(getInitialLanguage());
updateProjectArrows();
